export function resolveUserTimeZone(country?: string, city?: string): string {
  if (country && city && CITY_TIMEZONE_OVERRIDES[country]?.[city]) {
    return CITY_TIMEZONE_OVERRIDES[country][city];
  }
  if (country && COUNTRY_TIMEZONE_MAP[country]) {
    return COUNTRY_TIMEZONE_MAP[country];
  }
  return 'Asia/Kolkata';
}

export function getCountryLocalDateTime(date: Date, timeZone: string): {
  dateStr: string;
  timeStr: string;
  timeStrShort: string;
} {
  try {
    const formatter = new Intl.DateTimeFormat('en-CA', {
      timeZone,
      year: 'numeric',
      month: '2-digit',
      day: '2-digit',
      hour: '2-digit',
      minute: '2-digit',
      second: '2-digit',
      hour12: false,
    });
    const parts = formatter.formatToParts(date);
    let y = 1970, m = 1, d = 1, h = 0, min = 0, s = 0;
    for (const p of parts) {
      if (p.type === 'year') y = Number(p.value);
      if (p.type === 'month') m = Number(p.value);
      if (p.type === 'day') d = Number(p.value);
      if (p.type === 'hour') h = Number(p.value);
      if (p.type === 'minute') min = Number(p.value);
      if (p.type === 'second') s = Number(p.value);
    }
    const dateStr = `${y}-${String(m).padStart(2, '0')}-${String(d).padStart(2, '0')}`;
    const timeStr = `${String(h).padStart(2, '0')}:${String(min).padStart(2, '0')}:${String(s).padStart(2, '0')}`;
    const timeStrShort = `${String(h).padStart(2, '0')}:${String(min).padStart(2, '0')}`;
    return { dateStr, timeStr, timeStrShort };
  } catch {
    const y = date.getFullYear();
    const m = date.getMonth() + 1;
    const d = date.getDate();
    const h = date.getHours();
    const min = date.getMinutes();
    const s = date.getSeconds();
    const dateStr = `${y}-${String(m).padStart(2, '0')}-${String(d).padStart(2, '0')}`;
    const timeStr = `${String(h).padStart(2, '0')}:${String(min).padStart(2, '0')}:${String(s).padStart(2, '0')}`;
    const timeStrShort = `${String(h).padStart(2, '0')}:${String(min).padStart(2, '0')}`;
    return { dateStr, timeStr, timeStrShort };
  }
}

export function isElectionActiveInCountry(
  schedule: any,
  country?: string,
  city?: string,
  now = new Date()
): {
  isActive: boolean;
  status: 'no_election' | 'not_started' | 'active' | 'ended';
  message: string;
  timeZone: string;
  country: string;
  localTime: string;
} {
  const activeCountry = country || 'India';
  const timeZone = resolveUserTimeZone(activeCountry, city);
  const local = getCountryLocalDateTime(now, timeZone);

  if (!schedule || schedule.status !== 'active') {
    return {
      isActive: false,
      status: 'no_election',
      message: 'No active election is currently scheduled.',
      timeZone,
      country: activeCountry,
      localTime: local.timeStrShort,
    };
  }

  const normFrom = schedule.fromTime.length === 4 ? `0${schedule.fromTime}` : schedule.fromTime.slice(0, 5);
  const normTo = schedule.toTime.length === 4 ? `0${schedule.toTime}` : schedule.toTime.slice(0, 5);

  if (local.dateStr < schedule.date) {
    return {
      isActive: false,
      status: 'not_started',
      message: `Election in ${activeCountry} has not started yet. Voting opens on ${schedule.date} at ${schedule.fromTime} local time.`,
      timeZone,
      country: activeCountry,
      localTime: local.timeStrShort,
    };
  }

  if (local.dateStr > schedule.date) {
    return {
      isActive: false,
      status: 'ended',
      message: `Election in ${activeCountry} has ended. Voting closed on ${schedule.date} at ${schedule.toTime} local time.`,
      timeZone,
      country: activeCountry,
      localTime: local.timeStrShort,
    };
  }

  if (local.timeStrShort < normFrom) {
    return {
      isActive: false,
      status: 'not_started',
      message: `Election in ${activeCountry} opens today at ${schedule.fromTime} local time. Current local time: ${local.timeStrShort}.`,
      timeZone,
      country: activeCountry,
      localTime: local.timeStrShort,
    };
  }

  if (local.timeStrShort > normTo) {
    return {
      isActive: false,
      status: 'ended',
      message: `Election in ${activeCountry} has ended. Voting closed at ${schedule.toTime} local time.`,
      timeZone,
      country: activeCountry,
      localTime: local.timeStrShort,
    };
  }

  return {
    isActive: true,
    status: 'active',
    message: `Election is ACTIVE in ${activeCountry}. Voting is open until ${schedule.toTime} local time.`,
    timeZone,
    country: activeCountry,
    localTime: local.timeStrShort,
  };
}

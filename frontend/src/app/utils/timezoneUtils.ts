/**
 * Evaluates whether election results are ready to be published.
 * MUST strictly follow India Standard Time (IST / GMT+5:30) only, regardless of
 * the viewer's or voter's country timezone.
 */
export function getResultReleaseStatus(
  schedule: { resultDate?: string; resultTime?: string } | null,
  now: Date = new Date()
): ResultReleaseStatus {
  const indiaTime = formatRegionalTime(now, 'Asia/Kolkata');

  if (!schedule || !schedule.resultDate || !schedule.resultTime) {
    return {
      isConfigured: false,
      isReleased: true, // If no release date is configured, do not block
      resultDate: '',
      resultTime: '',
      resultFormattedDate: '',
      resultFormattedTime12: '',
      releaseTimestamp: 0,
      indiaCurrentTime12: indiaTime.time12,
      indiaCurrentDate: indiaTime.fullDate,
      indiaDayName: indiaTime.dayName,
      diffMs: 0,
      days: 0,
      hours: 0,
      minutes: 0,
      seconds: 0,
      countdownFormatted: '00d 00h 00m 00s',
    };
  }

  const timePart = schedule.resultTime.length === 5 ? `${schedule.resultTime}:00` : schedule.resultTime;
  // Parse strictly in India Standard Time (+05:30)
  const releaseTimestamp = new Date(`${schedule.resultDate}T${timePart}+05:30`).getTime();
  const currentTimestamp = now.getTime();
  const diffMs = releaseTimestamp - currentTimestamp;
  const isReleased = diffMs <= 0;

  const totalSeconds = Math.max(0, Math.floor(diffMs / 1000));
  const days = Math.floor(totalSeconds / 86400);
  const hours = Math.floor((totalSeconds % 86400) / 3600);
  const minutes = Math.floor((totalSeconds % 3600) / 60);
  const seconds = totalSeconds % 60;

  const countdownFormatted = `${days}d ${String(hours).padStart(2, '0')}h ${String(minutes).padStart(2, '0')}m ${String(seconds).padStart(2, '0')}s`;

  return {
    isConfigured: true,
    isReleased,
    resultDate: schedule.resultDate,
    resultTime: schedule.resultTime,
    resultFormattedDate: new Date(schedule.resultDate + 'T00:00:00').toLocaleDateString('en-IN', {
      weekday: 'long',
      year: 'numeric',
      month: 'long',
      day: 'numeric',
    }),
    resultFormattedTime12: formatTime12(schedule.resultTime),
    releaseTimestamp,
    indiaCurrentTime12: indiaTime.time12,
    indiaCurrentDate: indiaTime.fullDate,
    indiaDayName: indiaTime.dayName,
    diffMs: Math.max(0, diffMs),
    days,
    hours,
    minutes,
    seconds,
    countdownFormatted,
  };
}

/**
 * Converts a date string and time string in a specific IANA timezone into a UTC Date object.
 */
export function parseZonedTimeToUtc(dateStr: string, timeStr: string, timeZone: string): Date {
  if (!dateStr || !timeStr) return new Date();
  const [y, m, d] = dateStr.split('-').map(Number);
  const [h, min] = timeStr.split(':').map(Number);
  const safeH = isNaN(h) ? 0 : h;
  const safeMin = isNaN(min) ? 0 : min;

  const guessUtc = Date.UTC(y, (m || 1) - 1, d || 1, safeH, safeMin, 0);

  try {
    const local = getCountryLocalDateTime(new Date(guessUtc), timeZone);
    const localUtcRepresentation = Date.UTC(
      local.year,
      local.month - 1,
      local.day,
      local.hours,
      local.minutes,
      local.seconds
    );
    const offsetMs = localUtcRepresentation - guessUtc;
    return new Date(guessUtc - offsetMs);
  } catch {
    return new Date(guessUtc);
  }
}

export interface ConvertedIndiaTimeResult {
  utcDate: Date;
  indiaDateStr: string;
  indiaTimeStr: string;
  indiaTime12: string;
  indiaFullDate: string;
  country: string;
  countryTimeZone: string;
  isFasterThanIndia: boolean;
  offsetHoursDiff: number;
}

/**
 * Converts a foreign country's local date and time into India Standard Time (IST / GMT+5:30).
 */
export function convertTimeToIndiaTime(
  dateStr: string,
  timeStr: string,
  country: string = 'India',
  city?: string
): ConvertedIndiaTimeResult {
  const activeCountry = country || 'India';
  const timeZone = resolveUserTimeZone(activeCountry, city);
  const utcDate = parseZonedTimeToUtc(dateStr, timeStr, timeZone);
  const indiaLocal = getCountryLocalDateTime(utcDate, 'Asia/Kolkata');
  const indiaFormatted = formatRegionalTime(utcDate, 'Asia/Kolkata');

  const countryNow = getCountryLocalDateTime(utcDate, timeZone);
  const countryLocalUtc = Date.UTC(countryNow.year, countryNow.month - 1, countryNow.day, countryNow.hours, countryNow.minutes);
  const indiaLocalUtc = Date.UTC(indiaLocal.year, indiaLocal.month - 1, indiaLocal.day, indiaLocal.hours, indiaLocal.minutes);
  const diffHours = (countryLocalUtc - indiaLocalUtc) / (1000 * 60 * 60);

  return {
    utcDate,
    indiaDateStr: indiaLocal.dateStr,
    indiaTimeStr: indiaLocal.timeStrShort,
    indiaTime12: formatTime12(indiaLocal.timeStrShort),
    indiaFullDate: indiaFormatted.fullDate,
    country: activeCountry,
    countryTimeZone: timeZone,
    isFasterThanIndia: diffHours > 0,
    offsetHoursDiff: Math.round(diffHours * 10) / 10,
  };
}



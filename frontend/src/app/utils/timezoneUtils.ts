export interface FormattedTimeData {
  time12: string; // e.g. "09:35:42 PM"
  hours: string; // e.g. "09"
  minutes: string; // e.g. "35"
  seconds: string; // e.g. "42"
  ampm: string; // e.g. "PM"
  fullDate: string; // e.g. "Tuesday, September 22, 2026"
  shortDate: string; // e.g. "22 Sep 2026"
  dayName: string; // e.g. "Tuesday"
  timeZoneLabel: string; // e.g. "Gulf Standard Time"
  gmtOffset: string; // e.g. "GMT+4" or "UTC+04:00"
}

/**
 * Formats a Date into 12-hour format with seconds and detailed timezone information
 */
export function formatRegionalTime(date: Date, timeZone: string): FormattedTimeData {
  let hours = '12';
  let minutes = '00';
  let seconds = '00';
  let ampm = 'AM';
  let gmtOffset = '';
  let timeZoneLabel = '';

  try {
    const parts = new Intl.DateTimeFormat('en-US', {
      timeZone,
      hour: '2-digit',
      minute: '2-digit',
      second: '2-digit',
      hour12: true,
      timeZoneName: 'shortOffset',
    }).formatToParts(date);

    for (const part of parts) {
      if (part.type === 'hour') hours = part.value;
      if (part.type === 'minute') minutes = part.value;
      if (part.type === 'second') seconds = part.value;
      if (part.type === 'dayPeriod') ampm = part.value.toUpperCase();
      if (part.type === 'timeZoneName') gmtOffset = part.value;
    }
  } catch {
    // Fallback if timezone string is invalid
    const h = date.getHours();
    hours = String(h % 12 || 12).padStart(2, '0');
    minutes = String(date.getMinutes()).padStart(2, '0');
    seconds = String(date.getSeconds()).padStart(2, '0');
    ampm = h >= 12 ? 'PM' : 'AM';
  }

  try {
    const nameFormatter = new Intl.DateTimeFormat('en-US', {
      timeZone,
      timeZoneName: 'long',
    });
    const formattedWithLongName = nameFormatter.format(date);
    const split = formattedWithLongName.split(', ');
    if (split.length > 1) {
      timeZoneLabel = split[split.length - 1];
    }
  } catch {
    timeZoneLabel = timeZone;
  }

  let fullDate = '';
  let shortDate = '';
  let dayName = '';

  try {
    fullDate = new Intl.DateTimeFormat('en-US', {
      timeZone,
      weekday: 'long',
      year: 'numeric',
      month: 'long',
      day: 'numeric',
    }).format(date);

    shortDate = new Intl.DateTimeFormat('en-US', {
      timeZone,
      day: 'numeric',
      month: 'short',
      year: 'numeric',
    }).format(date);

    dayName = new Intl.DateTimeFormat('en-US', {
      timeZone,
      weekday: 'long',
    }).format(date);
  } catch {
    fullDate = date.toDateString();
    shortDate = date.toLocaleDateString();
    dayName = '';
  }

  return {
    time12: `${hours}:${minutes}:${seconds} ${ampm}`,
    hours,
    minutes,
    seconds,
    ampm,
    fullDate,
    shortDate,
    dayName,
    timeZoneLabel: timeZoneLabel || gmtOffset || timeZone,
    gmtOffset: gmtOffset || 'UTC',
  };
}

/**
 * Extracts local date and time components (YYYY-MM-DD, HH:MM:SS) in a specific IANA timezone
 */
export function getCountryLocalDateTime(date: Date, timeZone: string): {
  dateStr: string; // "YYYY-MM-DD"
  timeStr: string; // "HH:MM:SS"
  timeStrShort: string; // "HH:MM"
  year: number;
  month: number;
  day: number;
  hours: number;
  minutes: number;
  seconds: number;
} {
  try {
    const formatter = new Intl.DateTimeFormat('en-CA', {
      timeZone,
      year: 'numeric',
      month: '2-digit',
      day: '2-digit',
      hour: '2-digit',
      minute: '2-digit',
      second: '2-digit',
      hour12: false,
    });
    const parts = formatter.formatToParts(date);
    let y = 1970, m = 1, d = 1, h = 0, min = 0, s = 0;
    for (const p of parts) {
      if (p.type === 'year') y = Number(p.value);
      if (p.type === 'month') m = Number(p.value);
      if (p.type === 'day') d = Number(p.value);
      if (p.type === 'hour') h = Number(p.value);
      if (p.type === 'minute') min = Number(p.value);
      if (p.type === 'second') s = Number(p.value);
    }
    const dateStr = `${y}-${String(m).padStart(2, '0')}-${String(d).padStart(2, '0')}`;
    const timeStr = `${String(h).padStart(2, '0')}:${String(min).padStart(2, '0')}:${String(s).padStart(2, '0')}`;
    const timeStrShort = `${String(h).padStart(2, '0')}:${String(min).padStart(2, '0')}`;
    return {
      dateStr,
      timeStr,
      timeStrShort,
      year: y,
      month: m,
      day: d,
      hours: h,
      minutes: min,
      seconds: s,
    };
  } catch {
    const y = date.getFullYear();
    const m = date.getMonth() + 1;
    const d = date.getDate();
    const h = date.getHours();
    const min = date.getMinutes();
    const s = date.getSeconds();
    const dateStr = `${y}-${String(m).padStart(2, '0')}-${String(d).padStart(2, '0')}`;
    const timeStr = `${String(h).padStart(2, '0')}:${String(min).padStart(2, '0')}:${String(s).padStart(2, '0')}`;
    const timeStrShort = `${String(h).padStart(2, '0')}:${String(min).padStart(2, '0')}`;
    return { dateStr, timeStr, timeStrShort, year: y, month: m, day: d, hours: h, minutes: min, seconds: s };
  }
}

export function formatTime12(t: string): string {
  if (!t) return '';
  const [hStr, mStr] = t.split(':');
  const h = Number(hStr);
  const m = Number(mStr || 0);
  const ampm = h >= 12 ? 'PM' : 'AM';
  const hh = h % 12 || 12;
  return `${hh}:${String(m).padStart(2, '0')} ${ampm}`;
}

export interface CountryElectionStatusResult {
  status: 'no_election' | 'not_started' | 'active' | 'ended';
  country: string;
  city: string;
  timeZone: string;
  timeZoneLabel: string;
  gmtOffset: string;
  countryFlag: string;
  localDateStr: string;
  localTimeStr: string;
  localFormattedDate: string;
  localFormattedTime12: string;
  fromTimeFormatted: string;
  toTimeFormatted: string;
  message: string;
}

/**
 * Computes election status based on a specific country's local time rather than Indian time.
 * When the admin schedules an election (e.g. 7:00 AM – 7:00 PM), each country's voting window
 * opens when that country's local clock reaches the start time, and closes when that country's
 * local clock reaches the end time.
 */
export function getCountryElectionStatus(
  schedule: {
    date?: string;
    fromTime?: string;
    toTime?: string;
    status?: string;
    [key: string]: any;
  } | null,
  country?: string,
  city?: string,
  now: Date = new Date()
): CountryElectionStatusResult {
  const activeCountry = country || 'India';
  const activeCity = city !== undefined ? city : getDefaultCityForCountry(activeCountry);
  const timeZone = resolveUserTimeZone(activeCountry, activeCity);
  const timeData = formatRegionalTime(now, timeZone);
  const local = getCountryLocalDateTime(now, timeZone);
  const countryFlag = getCountryFlag(activeCountry);

  const fromTimeFormatted = formatTime12(schedule?.fromTime || '');
  const toTimeFormatted = formatTime12(schedule?.toTime || '');

  const baseResult = {
    country: activeCountry,
    city: activeCity,
    timeZone,
    timeZoneLabel: timeData.timeZoneLabel,
    gmtOffset: timeData.gmtOffset,
    countryFlag,
    localDateStr: local.dateStr,
    localTimeStr: local.timeStrShort,
    localFormattedDate: timeData.fullDate,
    localFormattedTime12: `${timeData.hours}:${timeData.minutes}:${timeData.seconds} ${timeData.ampm}`,
    fromTimeFormatted,
    toTimeFormatted,
  };

  if (!schedule) {
    return {
      ...baseResult,
      status: 'no_election',
      message: 'No election is currently scheduled.',
    };
  }

  if (schedule.status === 'ended') {
    return {
      ...baseResult,
      status: 'ended',
      message: `Election has ended.`,
    };
  }

  const normFrom = schedule.fromTime
    ? (schedule.fromTime.length === 4 ? `0${schedule.fromTime}` : schedule.fromTime.slice(0, 5))
    : '';
  const normTo = schedule.toTime
    ? (schedule.toTime.length === 4 ? `0${schedule.toTime}` : schedule.toTime.slice(0, 5))
    : '';

  // Handle "All Countries" global rolling schedule
  if (activeCountry === 'All Countries') {
    if (!schedule.date || !normFrom || !normTo) {
      return {
        ...baseResult,
        status: schedule.status === 'active' ? 'active' : 'no_election',
        message: 'Election is configured for all countries across the world.',
      };
    }

    // World timezones range from UTC+14 (earliest, Kiribati) to UTC-11 (latest, Niue/Samoa)
    const earliestStartUtc = parseZonedTimeToUtc(schedule.date, normFrom, 'Pacific/Kiritimati');
    const latestEndUtc = parseZonedTimeToUtc(schedule.date, normTo, 'Pacific/Niue');

    if (now.getTime() < earliestStartUtc.getTime()) {
      return {
        ...baseResult,
        status: 'not_started',
        message: `Voting across all countries opens on ${schedule.date} at ${fromTimeFormatted} in each country's local time.`,
      };
    }

    if (now.getTime() > latestEndUtc.getTime()) {
      return {
        ...baseResult,
        status: 'ended',
        message: `Voting has concluded across all countries worldwide (polls closed at ${toTimeFormatted} local time).`,
      };
    }

    return {
      ...baseResult,
      status: 'active',
      message: `Voting is ACTIVE worldwide! NRI voters across all countries vote according to their local country clock (${fromTimeFormatted} – ${toTimeFormatted}).`,
    };
  }

  // 1. If election date is in the future in voter's country:
  if (schedule.date && local.dateStr < schedule.date) {
    return {
      ...baseResult,
      status: 'not_started',
      message: `Voting in ${activeCountry} has not started yet. Polls open on ${schedule.date} at ${fromTimeFormatted} local time.`,
    };
  }

  // 2. If election date has already passed in voter's country:
  if (schedule.date && local.dateStr > schedule.date) {
    return {
      ...baseResult,
      status: 'ended',
      message: `Voting in ${activeCountry} has ended. Polls closed on ${schedule.date} at ${toTimeFormatted} local time.`,
    };
  }

  // 3. On election day (or if no specific date set):
  // Check if voter's current country local time is before start time
  if (normFrom && local.timeStrShort < normFrom) {
    return {
      ...baseResult,
      status: 'not_started',
      message: `Voting in ${activeCountry} has not started yet. Polls open today at ${fromTimeFormatted} local time. Current local time: ${baseResult.localFormattedTime12}.`,
    };
  }

  // Check if voter's current country local time is after end time
  if (normTo && local.timeStrShort > normTo) {
    return {
      ...baseResult,
      status: 'ended',
      message: `Voting in ${activeCountry} has ended. Polls closed at ${toTimeFormatted} local time.`,
    };
  }

  // Between start time and end time: voting is LIVE!
  return {
    ...baseResult,
    status: 'active',
    message: `Voting is ACTIVE in ${activeCountry}! Polls are open until ${toTimeFormatted} local time.`,
  };
}

/**
 * Automatically checks and stops the election in localStorage if the end time has passed.
 * When the end time has passed, status is automatically updated to 'ended' so manual stopping is not required.
 */
export function checkAndAutoStopElection(
  now: Date = new Date(),
  country?: string,
  city?: string
): { stopped: boolean; schedule: any } {
  try {
    const raw = typeof localStorage !== 'undefined' ? localStorage.getItem('electionSchedule') : null;
    if (!raw) return { stopped: false, schedule: null };
    const schedule = JSON.parse(raw);
    if (!schedule || !schedule.date || !schedule.toTime) {
      return { stopped: false, schedule };
    }

    if (schedule.status === 'ended') {
      return { stopped: false, schedule };
    }

    const targetCountry = country || schedule.country || (typeof localStorage !== 'undefined' ? localStorage.getItem('selectedPreviewCountry') : null);
    const targetCity = city || schedule.city || '';

    let isEnded = false;

    if (targetCountry) {
      const cStatus = getCountryElectionStatus(schedule, targetCountry, targetCity, now);
      if (cStatus.status === 'ended') {
        isEnded = true;
      }
    }

    if (!isEnded) {
      const [year, month, day] = schedule.date.split('-').map(Number);
      const [toH, toM] = schedule.toTime.split(':').map(Number);
      const end = new Date(year, month - 1, day, toH, toM, 0, 0);
      if (now.getTime() > end.getTime()) {
        isEnded = true;
      }
    }

    if (isEnded) {
      const updated = { ...schedule, status: 'ended', endedAt: Date.now(), autoStopped: true };
      localStorage.setItem('electionSchedule', JSON.stringify(updated));
      if (typeof window !== 'undefined') {
        window.dispatchEvent(new CustomEvent('electionScheduleUpdated', { detail: updated }));
      }
      return { stopped: true, schedule: updated };
    }

    return { stopped: false, schedule };
  } catch {
    return { stopped: false, schedule: null };
  }
}

/**
 * Determines real-time election operational status based on local time.
 * If the election end time has passed, it automatically marks the status as 'ended'
 * and updates localStorage so the election stops automatically.
 */
export function computeLiveElectionStatus(
  schedule: {
    date?: string;
    fromTime?: string;
    toTime?: string;
    status?: string;
    country?: string;
    city?: string;
  } | null,
  now: Date = new Date(),
  country?: string,
  city?: string
): 'no_election' | 'not_started' | 'active' | 'ended' {
  if (!schedule || !schedule.date || !schedule.fromTime || !schedule.toTime) {
    return 'no_election';
  }

  if (schedule.status === 'ended') {
    return 'ended';
  }

  const targetCountry = country || schedule.country || (typeof localStorage !== 'undefined' ? localStorage.getItem('selectedPreviewCountry') : null);
  const targetCity = city || schedule.city || '';

  if (targetCountry) {
    const cStatus = getCountryElectionStatus(schedule, targetCountry, targetCity, now);
    if (cStatus.status === 'ended') {
      checkAndAutoStopElection(now, targetCountry, targetCity);
      return 'ended';
    }
    return cStatus.status;
  }

  try {
    const [year, month, day] = schedule.date.split('-').map(Number);
    const [fromH, fromM] = schedule.fromTime.split(':').map(Number);
    const [toH, toM] = schedule.toTime.split(':').map(Number);

    const start = new Date(year, month - 1, day, fromH, fromM, 0, 0);
    const end = new Date(year, month - 1, day, toH, toM, 0, 0);

    if (now.getTime() < start.getTime()) {
      return 'not_started';
    }

    if (now.getTime() > end.getTime()) {
      // End time has passed -> Automatically stop election!
      checkAndAutoStopElection(now);
      return 'ended';
    }

    return 'active';
  } catch {
    return schedule.status === 'active' ? 'active' : 'no_election';
  }
}



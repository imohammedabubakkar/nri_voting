/**
 * Converts a 2-letter ISO country code into a unicode flag emoji.
 * On Windows, Chrome renders flag emoji pairs as clean 2-letter regional badges (e.g. IT, US, IN).
 */
export function isoCodeToFlagEmoji(isoCode: string): string {
  if (!isoCode || isoCode.length !== 2) return '🌍';
  try {
    const codePoints = isoCode
      .toUpperCase()
      .split('')
      .map(char => 127397 + char.charCodeAt(0));
    return String.fromCodePoint(...codePoints);
  } catch {
    return '🌍';
  }
}

/**
 * Safely adds days to a YYYY-MM-DD date string and returns the new YYYY-MM-DD date string.
 */
export function addDaysToDate(dateStr: string, days: number): string {
  if (!dateStr) return '';
  const [y, m, d] = dateStr.split('-').map(Number);
  if (!y || !m || !d) return '';
  const dt = new Date(Date.UTC(y, m - 1, d));
  dt.setUTCDate(dt.getUTCDate() + days);
  const resY = dt.getUTCFullYear();
  const resM = String(dt.getUTCMonth() + 1).padStart(2, '0');
  const resD = String(dt.getUTCDate()).padStart(2, '0');
  return `${resY}-${resM}-${resD}`;
}


/**
 * Gets the browser's current physical timezone
 */
export function getBrowserTimeZone(): string {
  try {
    return Intl.DateTimeFormat().resolvedOptions().timeZone || 'Asia/Kolkata';
  } catch {
    return 'Asia/Kolkata';
  }
}

/**
 * Resolves the appropriate IANA timezone for a user based on their country and city
 */
export function resolveUserTimeZone(country?: string, city?: string): string {
  if (country && city && CITY_TIMEZONE_OVERRIDES[country]?.[city]) {
    return CITY_TIMEZONE_OVERRIDES[country][city];
  }
  if (country && COUNTRY_TIMEZONE_MAP[country]) {
    return COUNTRY_TIMEZONE_MAP[country];
  }
  return getBrowserTimeZone();
}

export interface FormattedTimeData {
  time12: string; // e.g. "09:35:42 PM"
  hours: string; // e.g. "09"
  minutes: string; // e.g. "35"
  seconds: string; // e.g. "42"
  ampm: string; // e.g. "PM"
  fullDate: string; // e.g. "Tuesday, September 22, 2026"
  shortDate: string; // e.g. "22 Sep 2026"
  dayName: string; // e.g. "Tuesday"
  timeZoneLabel: string; // e.g. "Gulf Standard Time"
  gmtOffset: string; // e.g. "GMT+4" or "UTC+04:00"
}

/**
 * Formats a Date into 12-hour format with seconds and detailed timezone information
 */
export function formatRegionalTime(date: Date, timeZone: string): FormattedTimeData {
  let hours = '12';
  let minutes = '00';
  let seconds = '00';
  let ampm = 'AM';
  let gmtOffset = '';
  let timeZoneLabel = '';

  try {
    const parts = new Intl.DateTimeFormat('en-US', {
      timeZone,
      hour: '2-digit',
      minute: '2-digit',
      second: '2-digit',
      hour12: true,
      timeZoneName: 'shortOffset',
    }).formatToParts(date);

    for (const part of parts) {
      if (part.type === 'hour') hours = part.value;
      if (part.type === 'minute') minutes = part.value;
      if (part.type === 'second') seconds = part.value;
      if (part.type === 'dayPeriod') ampm = part.value.toUpperCase();
      if (part.type === 'timeZoneName') gmtOffset = part.value;
    }
  } catch {
    // Fallback if timezone string is invalid
    const h = date.getHours();
    hours = String(h % 12 || 12).padStart(2, '0');
    minutes = String(date.getMinutes()).padStart(2, '0');
    seconds = String(date.getSeconds()).padStart(2, '0');
    ampm = h >= 12 ? 'PM' : 'AM';
  }

  try {
    const nameFormatter = new Intl.DateTimeFormat('en-US', {
      timeZone,
      timeZoneName: 'long',
    });
    const formattedWithLongName = nameFormatter.format(date);
    const split = formattedWithLongName.split(', ');
    if (split.length > 1) {
      timeZoneLabel = split[split.length - 1];
    }
  } catch {
    timeZoneLabel = timeZone;
  }

  let fullDate = '';
  let shortDate = '';
  let dayName = '';

  try {
    fullDate = new Intl.DateTimeFormat('en-US', {
      timeZone,
      weekday: 'long',
      year: 'numeric',
      month: 'long',
      day: 'numeric',
    }).format(date);

    shortDate = new Intl.DateTimeFormat('en-US', {
      timeZone,
      day: 'numeric',
      month: 'short',
      year: 'numeric',
    }).format(date);

    dayName = new Intl.DateTimeFormat('en-US', {
      timeZone,
      weekday: 'long',
    }).format(date);
  } catch {
    fullDate = date.toDateString();
    shortDate = date.toLocaleDateString();
    dayName = '';
  }

  return {
    time12: `${hours}:${minutes}:${seconds} ${ampm}`,
    hours,
    minutes,
    seconds,
    ampm,
    fullDate,
    shortDate,
    dayName,
    timeZoneLabel: timeZoneLabel || gmtOffset || timeZone,
    gmtOffset: gmtOffset || 'UTC',
  };
}
